    /// <summary>Nombre de zombies à tuer à la manche donnée, pour le nombre de joueurs donné.
    /// La manche est bornée à [1, 255] (au-delà, on renvoie la valeur de la manche 255) et
    /// le nombre de joueurs à [1, 4].</summary>
    public static int GetCount(int round, int players)
    {
        var (r, p) = Clamped(round, players);
        return Table[r, p];
    }

    /// <summary>Nombre de hordes à la manche donnée, pour le nombre de joueurs donné.</summary>
    public static double GetHordes(int round, int players)
    {
        var (r, p) = Clamped(round, players);
        return HordesTable[r, p];
    }

    private static (int r, int p) Clamped(int round, int players) =>
        (Math.Clamp(round, MinRound, MaxRound) - 1, Math.Clamp(players, 1, 4) - 1);
